import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = new URL('../', import.meta.url);
execFileSync(process.execPath, ['scripts/build-browser-extension.js', '--check'], { cwd: fileURLToPath(root), stdio: 'inherit' });
const source = await fs.readFile(new URL('browser-extension/auditor.browser.js', root), 'utf8');
const output = `// Generated by scripts/build-website-scanner.mjs. Preserve bundled licenses.\nconst window = {};\nconst require = () => { throw new Error('Optional Node modules are unavailable in browser analysis'); };\n${source}\nexport { auditEvidence };\n`;
const destination = new URL('website/scanner/engine.mjs', root);
if (process.argv.includes('--check')) {
  if (await fs.readFile(destination, 'utf8') !== output) throw new Error('Website scanner engine is stale. Run node scripts/build-website-scanner.mjs');
  console.log('Website scanner engine is current.');
} else { await fs.mkdir(new URL('website/scanner/', root), { recursive: true }); await fs.writeFile(destination, output); }
